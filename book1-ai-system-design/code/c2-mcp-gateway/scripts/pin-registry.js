#!/usr/bin/env node
// pin-registry.js
//
// The APPROVAL step. Run this after a person has reviewed the upstream
// server's tool descriptions. It connects to the upstream, prints every
// description for the reviewer, and writes config/approved-servers.json with
// the server version and a SHA-256 fingerprint per tool.
//
// For the demo it starts the bundled upstream in-process so it needs nothing
// else running. In real life you would point it at the server under review,
// and the registry change would go through a pull request with sign-off.

import { writeFileSync } from 'node:fs';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { startHttpServer } from '../upstream/hcp360/src/http.js';
import { toolFingerprint } from '../src/registry.js';

const PRODUCTION_URL = 'http://127.0.0.1:3101/mcp'; // where the gateway will find it

const { httpServer, url } = await startHttpServer({ port: 0 });
const client = new Client({ name: 'registry-pinner', version: '1.0.0' });
await client.connect(new StreamableHTTPClientTransport(new URL(url), {
  requestInit: { headers: { 'x-caller-user': 'platform.reviewer', 'x-caller-territories': 'T-NE-101' } },
}));

const version = client.getServerVersion();
const { tools } = await client.listTools();
const pinned = {};
for (const tool of tools) {
  pinned[tool.name] = { descriptionSha256: toolFingerprint(tool) };
  console.log(`\n${tool.name}\n  ${tool.description}\n  sha256 ${pinned[tool.name].descriptionSha256}`);
}

const registry = {
  _about: 'Approved upstream MCP servers. Generated by scripts/pin-registry.js after human review.',
  servers: [{
    name: 'hcp360',
    url: PRODUCTION_URL,
    version: version.version,
    approvedBy: 'platform.reviewer',
    approvedOn: '2026-10-20',
    tools: pinned,
  }],
};
writeFileSync(new URL('../config/approved-servers.json', import.meta.url), JSON.stringify(registry, null, 2) + '\n');
console.log(`\nPinned ${tools.length} tools from ${version.name} ${version.version} into config/approved-servers.json`);

await client.close();
httpServer.close();
